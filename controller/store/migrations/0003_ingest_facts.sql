-- Ingest staging and typed facts (DESIGN.md 3.1, 3.2).

CREATE UNLOGGED TABLE stage_raw (                   -- COPY target: one verbatim NDJSON line per row
    chunk_no int NOT NULL,
    line     text NOT NULL
);

CREATE TABLE ingested_chunk (                       -- exactly-once guard, same transaction as facts
    chunk_no       int PRIMARY KEY,
    kind           text NOT NULL CHECK (kind IN ('history', 'events')),
    events         int NOT NULL,
    first_event_id bigint,
    last_event_id  bigint,
    until_minute   int NOT NULL,
    bytes          bigint,
    ingested_wall  timestamptz NOT NULL DEFAULT now(),
    txn_ms         int
);

CREATE TABLE campaign (
    campaign_id                text PRIMARY KEY,
    wf                         smallint NOT NULL,
    created_minute             int NOT NULL,
    sim_day                    smallint NOT NULL,
    leads                      int NOT NULL,
    config_version_at_creation int NOT NULL
);

CREATE TABLE lead_dim (
    lead_sk          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id          text NOT NULL UNIQUE,
    person_id        text NOT NULL,
    wf               smallint NOT NULL,
    campaign_id      text NOT NULL,
    cell             smallint,
    created_minute   int NOT NULL,
    state            smallint NOT NULL DEFAULT 0 CHECK (state IN (0, 1, 2)),  -- 0 active 1 concluded 2 exhausted
    attempts         smallint NOT NULL DEFAULT 0,
    last_attempt_min int,
    concluded_min    int
);
CREATE INDEX lead_dim_active ON lead_dim (wf, cell) WHERE state = 0;

-- Post-D0 calls only (history calls go to rollups only, 3.1). Partitioned by sim_day: call
-- ensure_call_fact_partitions(0, last_day) at bootstrap; anything outside lands in the default
-- partition, so an insert never fails for want of a partition.
CREATE TABLE call_fact (
    event_id       bigint NOT NULL,
    wf             smallint NOT NULL,
    lead_sk        bigint,                          -- NULL: orphan call (lead not seen; counted in loop_step)
    minute         int NOT NULL,
    sim_day        smallint NOT NULL,
    hour           smallint NOT NULL,
    seg            smallint NOT NULL,               -- half of the dialling window: 2 * sim_day + (0 | 1)
    attempt_no     smallint NOT NULL,
    day_index      smallint NOT NULL,
    config_version int NOT NULL,
    cohort_code    smallint NOT NULL,
    cell           smallint,
    w              smallint NOT NULL,
    v              smallint NOT NULL,
    did            smallint NOT NULL,
    prompt         smallint NOT NULL,
    connected      bool NOT NULL,
    engaged        bool NOT NULL,
    interested     bool NOT NULL,
    flag           bool NOT NULL,
    adherence      real,
    duration_s     smallint NOT NULL,
    turns          smallint NOT NULL
) PARTITION BY RANGE (sim_day);
CREATE TABLE call_fact_default PARTITION OF call_fact DEFAULT;
CREATE INDEX call_fact_event_brin ON call_fact USING brin (event_id);
CREATE INDEX call_fact_minute_brin ON call_fact USING brin (minute);
CREATE INDEX call_fact_wf_lead ON call_fact (wf, lead_sk);

-- Creates call_fact_dNNN partitions for days first_day..last_day in the current schema.
-- Returns the number created. Idempotent.
CREATE FUNCTION ensure_call_fact_partitions(first_day int, last_day int) RETURNS int
LANGUAGE plpgsql AS $$
DECLARE
    d       int;
    created int := 0;
    sch     text := current_schema();
    part    text;
BEGIN
    FOR d IN first_day..last_day LOOP
        part := format('call_fact_d%s', lpad(d::text, 3, '0'));
        IF to_regclass(format('%I.%I', sch, part)) IS NULL THEN
            EXECUTE format('CREATE TABLE %I.%I PARTITION OF %I.call_fact FOR VALUES FROM (%s) TO (%s)',
                           sch, part, sch, d, d + 1);
            created := created + 1;
        END IF;
    END LOOP;
    RETURN created;
END $$;

CREATE TABLE config_event (                         -- config_changed events
    event_id     bigint PRIMARY KEY,
    wf           smallint NOT NULL,
    version      int NOT NULL,
    actor        text NOT NULL,
    changed_dims text[] NOT NULL DEFAULT '{}',
    proposal_id  text,
    approval_id  text,
    minute       int NOT NULL
);
CREATE INDEX config_event_wf_version ON config_event (wf, version);

CREATE TABLE approval_event (                       -- approval_decided events
    event_id    bigint PRIMARY KEY,
    approval_id text NOT NULL,
    wf          smallint NOT NULL,
    status      text NOT NULL,
    reasons     jsonb,
    minute      int NOT NULL                        -- the decide minute (the event's ts)
);
CREATE INDEX approval_event_approval ON approval_event (approval_id);

CREATE TABLE event_other (                          -- any other event type (forward compatibility)
    event_id bigint PRIMARY KEY,
    type     text NOT NULL,
    body     jsonb NOT NULL
);
