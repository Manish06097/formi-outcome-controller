-- scope: run
-- Learned state (DESIGN.md 3.2). Path-dependent statistics (CUSUMs, SPRT sums) are persisted
-- after every step, so a restart never forgets what was learned (constraint 8).

CREATE TABLE bootstrap (                            -- NULL completed_minute: rerun on start (idempotent)
    id               smallint PRIMARY KEY CHECK (id = 1),
    started_minute   int,
    completed_minute int,
    history_chunks   int,
    decision_id      bigint
);

CREATE TABLE experiment (                           -- 5.3
    exp_id             text PRIMARY KEY,
    wf                 smallint NOT NULL,
    dim                text NOT NULL CHECK (dim IN ('welcome_message', 'voice', 'caller_id', 'prompt_version')),
    arms               smallint[] NOT NULL,
    control            smallint NOT NULL,
    cohort_set_version int,
    state              text NOT NULL,
    started_version    int,
    started_minute     int,
    interrupted_by     int                          -- supervisor version that interrupted it
);

CREATE TABLE experiment_arm (
    exp_id            text NOT NULL REFERENCES experiment (exp_id),
    arm               smallint NOT NULL,
    scope             text NOT NULL,                -- 'population' or a cohort_key
    state             text NOT NULL CHECK (state IN ('live', 'frozen', 'removed', 'futile', 'winner', 'control')),
    share             real,
    first_dial_minute int,
    removed_minute    int,
    decision_id       bigint,
    PRIMARY KEY (exp_id, arm, scope)
);

CREATE TABLE winner_look (                          -- the doubling schedule survives a crash (5.5)
    exp_id      text NOT NULL REFERENCES experiment (exp_id),
    arm         smallint NOT NULL,
    scope       text NOT NULL,
    look_no     smallint NOT NULL,
    n_at_look   int NOT NULL,
    sim_minute  int NOT NULL,
    w1          real,
    w2          real,
    w3          real,
    passed      boolean NOT NULL,
    decision_id bigint,
    PRIMARY KEY (exp_id, arm, scope, look_no)
);

CREATE TABLE winner (
    winner_id      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    exp_id         text NOT NULL REFERENCES experiment (exp_id),
    wf             smallint NOT NULL,
    dim            text NOT NULL,
    arm            smallint NOT NULL,
    scope          text NOT NULL,
    look_no        smallint NOT NULL,
    declared_minute int NOT NULL,
    decision_id    bigint,
    proposal_id    text,
    state          text NOT NULL CHECK (state IN ('declared', 'promoted', 'rolled_back'))
);

CREATE TABLE holdout (                              -- 5.6
    wf            smallint NOT NULL,
    scope         text NOT NULL,
    dim           text NOT NULL,
    winner_id     bigint REFERENCES winner (winner_id),
    control       smallint NOT NULL,
    share         real NOT NULL,
    since_version int,
    state         text NOT NULL,
    PRIMARY KEY (wf, scope, dim)
);

CREATE TABLE posterior_snapshot (                   -- enough for replay-decision (9.6)
    snapshot_id   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wf            smallint NOT NULL,
    decision_id   bigint,
    kind          text NOT NULL CHECK (kind IN ('stationary', 'ew')),
    inputs        bytea,                            -- npz of the aggregated counts, weights and prior
    inputs_hash   text,
    mean          bytea,
    cov           bytea,
    summary       jsonb,
    seed          bigint,                           -- reduce derived seeds mod 2^63
    code_version  text,
    settings_hash text
);

CREATE TABLE decay_monitor (                        -- one-sided Page CUSUM per arm and scope (5.7)
    wf        smallint NOT NULL,
    scope     text NOT NULL,
    dim       text NOT NULL,
    arm       smallint NOT NULL,
    cusum     real NOT NULL DEFAULT 0,
    seg_last  smallint,
    theta_ref real,
    alarm     bool NOT NULL DEFAULT false,
    PRIMARY KEY (wf, scope, dim, arm)
);

CREATE TABLE did_state (                            -- 5.9
    wf           smallint NOT NULL,
    did          smallint NOT NULL,
    status       text NOT NULL CHECK (status IN ('unknown', 'probing', 'healthy', 'unhealthy', 'degraded', 'suspect')),
    r_hat        real,
    r_lcb        real,
    r_ucb        real,
    n_dials      int NOT NULL DEFAULT 0,
    sprt_llr     real NOT NULL DEFAULT 0,
    since_minute int,
    evidence     jsonb,
    PRIMARY KEY (wf, did)
);

CREATE TABLE drift_monitor (                        -- 7.5
    wf            smallint NOT NULL,
    kpi           text NOT NULL,
    cusum         real NOT NULL DEFAULT 0,          -- downward CUSUM (the alarm)
    up_cusum      real NOT NULL DEFAULT 0,          -- upward CUSUM (view only)
    last_block    int,
    baseline_kind text,
    alarm         bool NOT NULL DEFAULT false,
    PRIMARY KEY (wf, kpi)
);

CREATE TABLE flag_monitor (                         -- live Bernoulli flag CUSUM (7.1); added by M0
    wf                smallint PRIMARY KEY,
    prompt            smallint NOT NULL,            -- incumbent prompt the CUSUM was reset for
    p0                double precision NOT NULL,
    p1                double precision NOT NULL,
    h                 double precision NOT NULL,
    stat              double precision NOT NULL DEFAULT 0,
    flags_since_reset int NOT NULL DEFAULT 0,
    calls             bigint NOT NULL DEFAULT 0,
    last_event_id     bigint,
    alarm             bool NOT NULL DEFAULT false,
    reset_minute      int
);

CREATE TABLE baseline (
    wf              smallint NOT NULL,
    metric          text NOT NULL,
    scope           text NOT NULL,
    value           double precision,
    n               bigint,
    computed_minute int,
    PRIMARY KEY (wf, metric, scope)
);

CREATE TABLE incident (
    incident_id     text PRIMARY KEY,
    wf              smallint NOT NULL,
    kind            text NOT NULL,
    state           text NOT NULL,
    opened_minute   int NOT NULL,
    confirmed_minute int,
    resolved_minute int,
    evidence        jsonb,
    fix_proposal_id text,
    credits_spent   real NOT NULL DEFAULT 0
);
CREATE INDEX incident_wf_state ON incident (wf, state);

CREATE TABLE validation_run (                       -- every run, pass or fail, is kept (7.1)
    run_id      text PRIMARY KEY,                   -- val_NNNNN from the simulator
    wf          smallint NOT NULL,
    prompt      smallint NOT NULL,
    n           int NOT NULL,
    failures    int NOT NULL,
    pass_rate   real NOT NULL,
    purpose     text,                               -- screen | verdict | gate_evidence | ...
    stage       smallint,
    incident_id text,
    intent_id   bigint,
    sim_minute  int
);
CREATE INDEX validation_run_wf_prompt ON validation_run (wf, prompt);

CREATE TABLE prompt_verdict (                       -- cache; a single gate pass is never cached as SAFE
    wf              smallint NOT NULL,
    prompt          smallint NOT NULL,
    verdict         text NOT NULL CHECK (verdict IN ('SAFE', 'UNSAFE')),
    mode            text CHECK (mode IN ('sequential', 'full', 'stage1_only')),
    runs            text[] NOT NULL DEFAULT '{}',
    pooled_n        int NOT NULL,
    pooled_failures int NOT NULL,
    gate_run        text,
    decided_minute  int,
    PRIMARY KEY (wf, prompt)
);

CREATE TABLE credit_ledger (                        -- every spend names its pool (7.2)
    seq             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sim_minute      int NOT NULL,
    tenant          text NOT NULL,
    wf              smallint,
    pool            text NOT NULL CHECK (pool IN ('R', 'S', 'U')),
    purpose         text NOT NULL,
    cost            real NOT NULL,
    remaining_after real,
    intent_id       bigint
);

CREATE TABLE credit_envelope (                      -- ordered pools, filled once at start (7.2)
    pool     text NOT NULL CHECK (pool IN ('R', 'S', 'U')),
    tenant   text NOT NULL,                         -- '*' for shared pools
    allotted real NOT NULL,
    spent    real NOT NULL DEFAULT 0,
    mode     text NOT NULL DEFAULT 'normal' CHECK (mode IN ('normal', 'low')),
    PRIMARY KEY (pool, tenant)
);
