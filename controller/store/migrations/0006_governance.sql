-- scope: run
-- Governance and reliability (DESIGN.md 3.2, 6, 8).

CREATE TABLE patch (                                -- overlay patches (6.7)
    patch_id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wf                smallint NOT NULL,
    owner             text NOT NULL,                -- emitting module
    path              text[] NOT NULL,              -- {alloc,<cohort>,<dim>} | {prompt} | {hour_weights,<cohort>} | {cohorts}
    value             jsonb,
    class             smallint NOT NULL CHECK (class BETWEEN 0 AND 3),
    p0_rank           smallint CHECK (p0_rank IN (0, 1)),
    state             text NOT NULL,
    proposal_id       text,
    decision_id       bigint,
    supervisor_touch  int,                          -- supervisor version that invalidated it
    held_until_minute int,                          -- auto-release (6.1)
    hold_count        smallint NOT NULL DEFAULT 0,
    evidence          jsonb
);
CREATE INDEX patch_wf_state ON patch (wf, state);

CREATE TABLE path_owner (
    wf            smallint NOT NULL,
    path          text[] NOT NULL,
    owner         text NOT NULL,                    -- module name | supervisor
    since_version int,
    since_minute  int,
    PRIMARY KEY (wf, path)
);

CREATE TABLE cooldown (                             -- 6.7 step 4
    wf             smallint NOT NULL,
    path           text[] NOT NULL,
    until_minute   int NOT NULL,
    source_version int,
    reason         text,
    PRIMARY KEY (wf, path)
);

CREATE TABLE proposal (                             -- 6.1
    proposal_id         text PRIMARY KEY,
    wf                  smallint NOT NULL,
    class               smallint NOT NULL CHECK (class BETWEEN 0 AND 3),   -- 0 incident 1 rollback 2 promotion 3 routine
    route               text NOT NULL CHECK (route IN ('approval', 'auto')),
    state               text NOT NULL CHECK (state IN (
                            'draft', 'discarded', 'submitting', 'noticed', 'auto_applying', 'pending',
                            'approved', 'applying', 'applied', 'verifying', 'verified', 'rollback',
                            'rejected', 'expired', 'stale', 'lapsed_local', 'superseded', 'abandoned',
                            'failed', 'failed_policy')),
    base_version        int NOT NULL,
    proposed_config     jsonb,                      -- Config.stored(): the API keeps no bodies
    request             jsonb,                      -- the exact request body sent
    change_summary      text,
    diff                jsonb,
    affected_leads      int,
    dry_run             jsonb,
    impact_score        real,
    rationale           text,
    evidence            jsonb,
    approval_id         text,
    submitted_minute    int,
    decided_minute      int,
    apply_by_minute     int,
    notice_until_minute int,
    applied_version     int,
    superseded_by       text,
    requeued_from       text,
    decision_id         bigint,
    verify              jsonb
);
-- One change in flight per workflow, as a database invariant (3.2, 6.2). The only way past it is
-- to mark the holder superseded and insert the new proposal in the same transaction.
CREATE UNIQUE INDEX one_in_flight ON proposal (wf)
    WHERE state IN ('submitting', 'pending', 'approved', 'applying', 'noticed', 'auto_applying');
CREATE INDEX proposal_wf_state ON proposal (wf, state);
CREATE UNIQUE INDEX proposal_approval ON proposal (approval_id) WHERE approval_id IS NOT NULL;

CREATE TABLE proposal_transition (                  -- one row per transition, with an audit row
    proposal_id text NOT NULL REFERENCES proposal (proposal_id),
    seq         smallint NOT NULL,
    from_state  text,
    to_state    text NOT NULL,
    sim_minute  int NOT NULL,
    reason      text,
    decision_id bigint,
    PRIMARY KEY (proposal_id, seq)
);

CREATE TABLE approval_mirror (                      -- GET /approvals as last seen
    approval_id        text PRIMARY KEY,
    proposal_id        text UNIQUE,
    wf                 smallint NOT NULL,
    status             text NOT NULL,
    created_minute     int,
    expires_minute     int,
    decided_minute     int,
    apply_by_minute    int,
    reasons            jsonb,
    last_polled_minute int,
    approver_name      text                         -- the API never returns it; for the client's system
);

CREATE TABLE intent (                               -- write-ahead intents (8.2)
    intent_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind          text NOT NULL,
    idem_key      text NOT NULL UNIQUE,
    request       jsonb,
    status        text NOT NULL CHECK (status IN ('started', 'done', 'failed', 'aborted', 'unknown')),
    response      jsonb,
    decision_id   bigint,
    sim_minute    int NOT NULL,
    started_wall  timestamptz NOT NULL DEFAULT now(),
    finished_wall timestamptz
);
CREATE INDEX intent_open ON intent (intent_id) WHERE status = 'started';

CREATE TABLE hold (                                 -- supervisor holds; the only table ctl_api may write
    hold_id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    wf              smallint NOT NULL,
    set_by          text NOT NULL,
    reason          text,
    from_minute     int NOT NULL,
    until_minute    int,
    released_minute int
);
CREATE INDEX hold_wf_from ON hold (wf, from_minute);
