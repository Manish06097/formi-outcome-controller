-- scope: run
-- Audit and ops (DESIGN.md 3.2, 9).

CREATE TABLE decision (                             -- written before acting (8.2), including "no action"
    decision_id        bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sim_minute         int NOT NULL,
    wf                 smallint,
    module             text NOT NULL,
    kind               text NOT NULL,
    rule_id            text NOT NULL,
    inputs             jsonb,
    outcome            jsonb,
    harm_report        jsonb,
    parent_decision_id bigint,
    snapshot_ids       bigint[] NOT NULL DEFAULT '{}',
    seed               bigint,
    settings_hash      text NOT NULL,
    code_version       text NOT NULL
);
CREATE INDEX decision_wf_minute ON decision (wf, sim_minute);

CREATE TABLE audit_log (
    audit_id     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sim_minute   int NOT NULL,
    wall         timestamptz NOT NULL DEFAULT now(),
    wf           smallint,
    actor        text NOT NULL,
    action       text NOT NULL,
    subject_type text NOT NULL,
    subject_id   text NOT NULL,
    summary      text NOT NULL,
    details      jsonb,
    caused_by    bigint
);
CREATE INDEX audit_log_wf_minute ON audit_log (wf, sim_minute);
CREATE INDEX audit_log_subject ON audit_log (subject_type, subject_id);
CREATE INDEX audit_log_caused_by ON audit_log (caused_by) WHERE caused_by IS NOT NULL;

CREATE TABLE allocation_provenance (               -- materialised for EVERY cohort and dim of a version (9.4)
    wf            smallint NOT NULL,
    version       int NOT NULL,
    cohort_key    text NOT NULL,                    -- 'default' for the default cohort and for prompt_version
    dim           text NOT NULL,
    option        smallint NOT NULL,
    share         real NOT NULL,
    source        text NOT NULL CHECK (source IN ('default', 'arm', 'winner', 'holdout', 'probe', 'supervisor', 'rollback')),
    inherited     boolean NOT NULL,                 -- true: no override for dim; copied from 'default'
    experiment_id text,
    proposal_id   text,
    approval_id   text,
    decision_id   bigint,
    PRIMARY KEY (wf, version, cohort_key, dim, option)
);

CREATE TABLE loop_step (                            -- 9.1
    step_no             int PRIMARY KEY,
    from_minute         int NOT NULL,
    to_minute           int NOT NULL,
    phase_ms            jsonb,
    chunks              int,
    events              int,
    orphan_calls        int,
    decisions           int,
    proposals_submitted int,
    applies             int,
    credits_remaining   real,
    rss_mb              int,
    db_bytes            bigint,
    wall                timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE alert (                                -- 9.2; every alert carries its runbook anchor
    alert_id    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    severity    text NOT NULL CHECK (severity IN ('page', 'digest')),
    code        text NOT NULL,
    wf          smallint,
    sim_minute  int,
    opened_wall timestamptz NOT NULL DEFAULT now(),
    closed_wall timestamptz,
    message     text NOT NULL,
    runbook     text NOT NULL                       -- docs/RUNBOOK.md#<code>
);
CREATE INDEX alert_open ON alert (code) WHERE closed_wall IS NULL;

CREATE TABLE clock (
    id           smallint PRIMARY KEY CHECK (id = 1),
    sim_minute   int NOT NULL,
    end_minute   int NOT NULL,
    tick         int NOT NULL,
    last_step_no int
);

CREATE TABLE heartbeat (                            -- the 10 s heartbeat row (2, 9.1); added by M0
    id      smallint PRIMARY KEY CHECK (id = 1),
    wall    timestamptz NOT NULL,
    pid     int,
    step_no int
);
